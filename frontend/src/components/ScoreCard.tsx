import type { Analysis } from '../lib/api'

const metricLabels: { key: 'keyword_coverage' | 'section_completeness' | 'impact_score' | 'format_score'; label: string; tone: string }[] = [
  { key: 'keyword_coverage', label: 'Keyword coverage', tone: 'bg-primary' },
  { key: 'section_completeness', label: 'Section completeness', tone: 'bg-accent' },
  { key: 'impact_score', label: 'Impact density', tone: 'bg-success' },
  { key: 'format_score', label: 'Formatting', tone: 'bg-warning' },
]

export function ScoreCard({ analysis }: { analysis: Analysis }) {
  return (
    <section className="rounded-2xl border border-border bg-surface p-6">
      <div className="flex flex-wrap items-center gap-6">
        <ScoreRing value={analysis.ats_score} />
        <div>
          <h2 className="text-xl font-semibold tracking-tight">ATS readiness</h2>
          <p className="mt-1 text-sm text-muted">
            {analysis.company} · {analysis.role}
          </p>
          <p className="mt-2 max-w-md text-xs leading-relaxed text-muted">
            Transparent, rule-based heuristic. Not an actual ATS verdict, and not generated by
            the LLM.
          </p>
        </div>
      </div>

      <div className="mt-6 grid gap-4 sm:grid-cols-2">
        {metricLabels.map(({ key, label, tone }) => {
          const value = Math.round(analysis.score[key] * 100)
          return (
            <div key={key}>
              <div className="flex items-center justify-between text-xs text-muted">
                <span>{label}</span>
                <span className="font-semibold text-foreground">{value}%</span>
              </div>
              <div className="mt-1.5 h-2 overflow-hidden rounded-full bg-border">
                <div className={`h-full rounded-full ${tone}`} style={{ width: `${value}%` }} />
              </div>
            </div>
          )
        })}
      </div>

      <div className="mt-6 grid gap-4 sm:grid-cols-2">
        <KeywordGroup
          title="Matched keywords"
          keywords={analysis.matched_keywords}
          chipClass="bg-success/10 text-success ring-success/20"
          empty="No keywords recognized yet."
        />
        <KeywordGroup
          title="Missing keywords"
          keywords={analysis.missing_keywords}
          chipClass="bg-warning/10 text-warning ring-warning/20"
          empty="Nothing missing. Nice."
        />
      </div>
    </section>
  )
}

function KeywordGroup({
  title,
  keywords,
  chipClass,
  empty,
}: {
  title: string
  keywords: string[]
  chipClass: string
  empty: string
}) {
  return (
    <div>
      <h3 className="text-xs font-semibold uppercase tracking-wide text-muted">{title}</h3>
      {keywords.length === 0 ? (
        <p className="mt-2 text-xs text-muted">{empty}</p>
      ) : (
        <ul className="mt-2 flex flex-wrap gap-1.5">
          {keywords.map((keyword) => (
            <li
              key={keyword}
              className={`rounded-full px-2.5 py-1 text-xs font-medium ring-1 ${chipClass}`}
            >
              {keyword}
            </li>
          ))}
        </ul>
      )}
    </div>
  )
}

function ScoreRing({ value }: { value: number }) {
  return (
    <div
      className="grid size-24 shrink-0 place-items-center rounded-full"
      style={{
        background: `conic-gradient(var(--primary) 0 ${value}%, var(--surface-2) ${value}% 100%)`,
      }}
    >
      <div className="grid size-[4.6rem] place-items-center rounded-full bg-surface">
        <span className="text-2xl font-semibold tracking-tight">{value}</span>
      </div>
    </div>
  )
}
